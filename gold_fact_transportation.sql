with transport_table as (
    select *
    from {{ref("silver_transportation")}})

    , shipment_table as (
        select *
        from {{ref("gold_fact_shipments")}})

        , main_table as (
        select
        t.TRANSPORTATION_ID,
        t.ARRIVAL_DATE,
         t.DEPARTURE_DATE,
       t.DESTINATION_LOCATION,
       t.DISTANCE_KM,
       t.FUEL_COST,
       t.ORIGIN_WAREHOUSE_ID,
        t.SHIPMENT_ID,
          t.TRANSPORT_COST,
       t.TRANSPORT_MODE,
      t.TRANSPORT_STATUS,
      s.shipment_key,
        s.ACTUAL_DELIVERY_DATE,
        s.EXPECTED_DELIVERY_DATE,
        s.ORDER_ID,
        s.SHIP_DATE,
        s.SHIPMENT_STATUS,
       s.SHIPPING_COST,
         s.WAREHOUSE_ID,
        s.ORDER_KEY,
        s.CUSTOMER_ID,
        s.ORDER_DATE,
        s.ORDER_STATUS,
        s.PRIORITY,
       s.CUURENCY,     
        s.TOTAL_AMOUNT,
        s.CUSTOMER_KEY,
        s.shipment_method,
        s.NAME,
       s.COUNTRY,
        s.CITY,
        s.SEGMENT,
        s.STATUS,
         s.DATE,
        s.WAREHOUSE_KEy,
        s.WAREHOUSE_NAME,
        s.WAREHOUSE_TYPE,
        s.CAPCITY_UNITS,
            s.country1,
         s.status1,
        s.city1
        from transport_table as t 
        left join shipment_table as s 
        on t.shipment_id = s.shipment_id)

        select
        row_number() over (order by transportation_id) as transport_key,
           TRANSPORTATION_ID,
        ARRIVAL_DATE,
         DEPARTURE_DATE,
       DESTINATION_LOCATION,
       DISTANCE_KM,
       FUEL_COST,
       ORIGIN_WAREHOUSE_ID,
        SHIPMENT_ID,
          TRANSPORT_COST,
       TRANSPORT_MODE,
      TRANSPORT_STATUS,
      shipment_key,
        ACTUAL_DELIVERY_DATE,
        EXPECTED_DELIVERY_DATE,
        ORDER_ID,
        SHIP_DATE,
        SHIPMENT_STATUS,
       SHIPPING_COST,
         WAREHOUSE_ID,
        ORDER_KEY,
        CUSTOMER_ID,
        ORDER_DATE,
        ORDER_STATUS,
        PRIORITY,
       CUURENCY,     
        TOTAL_AMOUNT,
        CUSTOMER_KEY,
        shipment_method,
        NAME,
       COUNTRY,
       CITY,
       SEGMENT,
        STATUS,
         DATE,
        WAREHOUSE_KEy,
        WAREHOUSE_NAME,
        WAREHOUSE_TYPE,
        CAPCITY_UNITS,
      country1,
         status1,
       city1
       from main_table